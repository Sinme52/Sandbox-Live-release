const ri = (a, b) => Math.floor(a + Math.random() * (b - a + 1));
const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];

function shuffle(arr) {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = ri(0, i);
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

// 答えが n になる計算問題。level（食べた数）が増えるほど難しくなる。
export function makeMath(n, level) {
  const eq = (s) => `${s} = ？`;
  if (level < 16) {
    const forms = [
      () => { const b = ri(2, 9); return eq(`${n + b} − ${b}`); },
      () => { const k = ri(2, 9); return eq(`${n * k} ÷ ${k}`); },
    ];
    if (n >= 2) forms.push(() => { const a = ri(1, n - 1); return eq(`${a} + ${n - a}`); });
    return pick(forms)();
  }
  if (level < 40) {
    return pick([
      () => { const k = ri(3, 9); return `□ × ${k} = ${n * k}\n□に入る数は？`; },
      () => { const a = ri(3, 9); const b = ri(3, 9); return eq(`${a} × ${b} − ${a * b - n}`); },
      () => { const k = ri(2, 5); const m = ri(2, 9); return eq(`(${n * k + m} − ${m}) ÷ ${k}`); },
    ])();
  }
  return pick([
    () => eq(`√${n * n}`),
    () => { const k = ri(3, 9); const j = ri(2, 9); return eq(`${(n + j) * k} ÷ ${k} − ${j}`); },
    () => {
      const x = ri(4, 9);
      const y = ri(4, 9);
      const rest = x * y - n;
      const k = shuffle([2, 3, 4, 5, 6, 7]).find((v) => rest % v === 0 && rest / v >= 2);
      return k ? eq(`${x} × ${y} − ${k} × ${rest / k}`) : eq(`${x} × ${y} − ${rest}`);
    },
  ])();
}

// 答えが n になる数え問題
export function makeCount(n) {
  const kinds = shuffle(['🐙', '🦑', '🦀']);
  const list = Array(n).fill(kinds[0]);
  const others = ri(3, Math.max(3, 12 - n));
  for (let i = 0; i < others; i++) list.push(pick(kinds.slice(1)));
  return `${kinds[0]}はいくつ？\n${shuffle(list).join('')}`;
}

// 答えが n のクイズを1問選ぶ。used は出題済みの問題文。
export function pickQuiz(n, level, used) {
  const roll = Math.random();
  const pool = BANK[n].filter((q) => !used.has(q));
  let text;
  if (roll < 0.62 && pool.length) {
    text = pick(pool);
  } else if (roll < 0.74) {
    text = makeCount(n);
  } else {
    text = makeMath(n, level);
    for (let i = 0; i < 8 && used.has(text); i++) text = makeMath(n, level);
  }
  used.add(text);
  return { text, answer: n };
}
